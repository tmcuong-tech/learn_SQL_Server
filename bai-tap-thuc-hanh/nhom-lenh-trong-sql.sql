/*
sql co the chi thanh 4 nhom chinh, gom
DML (data manipulation language): thao tac voi data trong database, 
cac cau lenh chen, cap nhat, xao, truy van
- insert into: chen du lieu vao bang
- update: cap nhat du lieu trong bang
- delete: xoa du lieu tu mot bang
- select: truy van du lieu tu mot hoac nhieu bang

DDL (data definition language): dinh nghia cau truc cua database,
gom cac bang, cot, chi muc va rang buoc
- create table: tao bang moi
- alter table: them, xoa hoac sua cac cot trong bang
- drop table: xoa mot bang
- create index: tao mot chi muc cho mot cot haoc tap hop cac cot
- create constraint: tao mot rang buoc cho mot cot hoac tap hop cac cot
- drop constraint: xoa mot rang buoc

DCL (data control language): kiem soat quyen truy cap vao database,
gom cac lenh cap phep, thu hoi quyen
- grant: cap quyen truy cap cho nguoi dung
- revoke: thu hoi quyen truy cap cho nguoi dung

TCL (transaction control language): quan ly cac giao dich trong database,
gom cac cau lenh bat dau, xac nhan, hoan tac giao dich
begin transaction: bat dau mot giao dich
commit transaction: xac nhan mot giao dich
rollback transaction: hoan tac mot giao dich
*/